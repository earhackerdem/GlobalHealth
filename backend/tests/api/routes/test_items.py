def test_create_item_title_with_nul_is_422(db: Session) -> None:
    """Escenario «NUL en un elemento»: una persona con sesión crea un elemento
    con title que contiene \\u0000 -> 422 y no se crea.

    The client does not re-raise server exceptions: a NUL reaching Postgres
    shows up as a 500 instead of crashing the test."""
    email = random_email()
    password = random_lower_string()
    user = crud.create_user(
        session=db, user_create=UserCreate(email=email, password=password)
    )
    test_client = TestClient(app, raise_server_exceptions=False)
    headers = user_authentication_headers(
        client=test_client, email=email, password=password
    )

    response = test_client.post(
        f"{settings.API_V1_STR}/items/",
        headers=headers,
        json={"title": "Elemento\u0000", "description": "Descripción"},
    )

    assert response.status_code == 422, response.text
    with Session(engine) as fresh:
        owned = fresh.exec(select(Item).where(Item.owner_id == user.id)).all()
    assert owned == []
